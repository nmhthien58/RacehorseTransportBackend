-- SCRIPT 03: Tài liệu của sự cố + mức độ ban đầu (sức khỏe ngựa, giai đoạn a)
-- - incident.incident_documents: ảnh hiện trường, biên bản thú y, giấy chứng tử, giấy đủ sức đi tiếp.
--   Phương án Deceased cần ít nhất một VetReport hoặc DeathCertificate.
-- - trip_incidents.initial_severity: mức tài xế báo lúc đầu; severity có thể được nâng lên Critical khi duyệt Deceased.
-- Idempotent: chạy lại nhiều lần không sao. Database dựng mới bằng 01_schema.sql đã có sẵn.
-- =====================================================================================

ALTER TABLE incident.trip_incidents
    ADD COLUMN IF NOT EXISTS initial_severity varchar(10);

-- Sự cố cũ: mức ban đầu = mức hiện tại
UPDATE incident.trip_incidents SET initial_severity = severity WHERE initial_severity IS NULL;

CREATE TABLE IF NOT EXISTS incident.incident_documents (
    incident_document_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id          integer      NOT NULL REFERENCES incident.trip_incidents (incident_id),
    file_path            varchar(500) NOT NULL,
    document_type        varchar(20)  NOT NULL
        CONSTRAINT ck_incident_documents_type CHECK (document_type IN ('ScenePhoto', 'VetReport', 'DeathCertificate', 'FitToTravel')),
    note                 varchar(500),
    uploaded_by_user_id  integer      NOT NULL REFERENCES identity.users (user_id),
    uploaded_at          timestamptz  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_incident_documents_incident ON incident.incident_documents (incident_id);

-- Biên bản thú y gửi theo cách cũ (vet_report_path) cũng thành tài liệu VetReport
INSERT INTO incident.incident_documents (incident_id, file_path, document_type, uploaded_by_user_id, uploaded_at)
SELECT i.incident_id, i.vet_report_path, 'VetReport', COALESCE(i.approved_by_user_id, i.reported_by_user_id), COALESCE(i.approved_at, i.reported_at)
FROM incident.trip_incidents i
WHERE i.vet_report_path IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM incident.incident_documents d WHERE d.incident_id = i.incident_id AND d.file_path = i.vet_report_path);
