-- Phạm vi dịch vụ (R-18): nước khách chọn được làm nước đi / nước đến.
-- Nhận đường bộ / đường bay tới một nước hay không = dòng cước FREIGHT (theo phương thức, nước đến) đang bật trong pricing.price_items.
CREATE TABLE IF NOT EXISTS common.countries (
    country_code  char(2)      PRIMARY KEY CONSTRAINT ck_countries_code CHECK (country_code ~ '^[A-Z]{2}$'),
    name_vi       varchar(100) NOT NULL,
    name_en       varchar(100) NOT NULL,
    is_active     boolean      NOT NULL DEFAULT true,
    sort_order    integer      NOT NULL DEFAULT 0
);

-- Sân bay nhận ngựa của từng nước (R-18). Đường bay cần nước đi và nước đến đều có sân bay đang mở.
CREATE TABLE IF NOT EXISTS common.airports (
    airport_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_code  char(2)      NOT NULL REFERENCES common.countries (country_code),
    iata_code     char(3)      NOT NULL CONSTRAINT uq_airports_iata UNIQUE
                               CONSTRAINT ck_airports_iata CHECK (iata_code ~ '^[A-Z]{3}$'),
    name          varchar(150) NOT NULL,
    city          varchar(100),
    is_active     boolean      NOT NULL DEFAULT true
);

CREATE INDEX IF NOT EXISTS ix_airports_country ON common.airports (country_code);

