-- =====================================================================================

-- Bảng 15: Sự cố (gồm cả phương án xử lý và chi phí phát sinh)
CREATE TABLE incident.trip_incidents (
    incident_id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_code           varchar(30)   NOT NULL CONSTRAINT uq_trip_incidents_code UNIQUE,
    trip_id                 integer       NOT NULL REFERENCES fleet.trips (trip_id),
    reported_by_user_id     integer       NOT NULL REFERENCES identity.users (user_id),
    incident_type           varchar(30)   NOT NULL
        CONSTRAINT ck_trip_incidents_type CHECK (incident_type IN ('MechanicalBreakdown', 'BorderCongestion', 'EquineHealthIssue', 'Weather', 'ClimateControlFailure', 'CustomsHold', 'Other')),
    description             text          NOT NULL,
    location                varchar(255)  NOT NULL,
    proposed_action         varchar(255),
    -- Loại hành động của phương án; route_change = thay đổi tuyến đi kèm (bỏ / thêm mốc), áp vào lộ trình khi Manager duyệt
    response_action         varchar(30)
        CONSTRAINT ck_trip_incidents_response_action CHECK (response_action IN ('WaitAndContinue', 'RepairAndContinue', 'Reroute', 'VeterinaryCare', 'OffloadHorse', 'Other')),
    route_change            jsonb,
    revised_route_notes     text,
    additional_cost         numeric(18,2) NOT NULL DEFAULT 0,
    rejection_reason        varchar(500), -- lý do của lần Manager từ chối phương án gần nhất
    -- Vòng đời: Reported -> PlanProposed -> Approved | Rejected (đề xuất lại) -> Resolved
    status                  varchar(30)   NOT NULL DEFAULT 'Reported'
        CONSTRAINT ck_trip_incidents_status CHECK (status IN ('Reported', 'PlanProposed', 'Approved', 'Rejected', 'Resolved')),
    approved_by_user_id     integer REFERENCES identity.users (user_id),
    approved_at             timestamptz,
    reported_at             timestamptz   NOT NULL DEFAULT now(),
    severity                varchar(10)   NOT NULL DEFAULT 'Moderate'
        CONSTRAINT ck_trip_incidents_severity CHECK (severity IN ('Minor', 'Moderate', 'Major', 'Critical')),
    affected_trip_horse_id  integer REFERENCES fleet.trip_horses (trip_horse_id),
    resolved_at             timestamptz,
    -- Phương án OffloadHorse (R-12): hướng xử lý tiếp + biên bản thú y (bắt buộc khi Deceased)
    offload_outcome         varchar(20)
        CONSTRAINT ck_trip_incidents_offload_outcome CHECK (offload_outcome IN ('WaitRecover', 'ReturnToOrigin', 'HandOverHere', 'Deceased')),
    vet_report_path         varchar(500),
    emergency_offload       boolean       NOT NULL DEFAULT false -- tài xế đã dỡ con ngựa ngay lúc báo sự cố
);

