-- Bảng 18: Bảng giá. Mỗi dòng là một khoản giá: cước tuyến, hệ số hạng chuồng, phụ phí,
-- chiết khấu, phí thủ tục, phí áp tải, bảo hiểm.
--   transport_mode    NULL = áp dụng cho cả đường bộ và đường bay
--   dest_country_code NULL = áp dụng cho mọi nước đến (dòng có nước cụ thể được ưu tiên hơn)
CREATE TABLE pricing.price_items (
    price_item_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category           varchar(20)   NOT NULL
        CONSTRAINT ck_price_items_category CHECK (category IN ('Freight', 'StallClass', 'Surcharge', 'Discount', 'Clearance', 'Escort', 'Insurance')),
    item_code          varchar(30)   NOT NULL,
    item_name          varchar(100)  NOT NULL,
    transport_mode     varchar(10)
        CONSTRAINT ck_price_items_mode CHECK (transport_mode IN ('Ground', 'Air')),
    dest_country_code  char(2),
    calc_type          varchar(20)   NOT NULL
        CONSTRAINT ck_price_items_calc_type CHECK (calc_type IN ('PerHorse', 'PerKmPerHorse', 'Multiplier', 'Percent', 'PerBooking', 'PerGroom', 'PerGroomDay')),
    value              numeric(18,4) NOT NULL,
    min_horses         integer,      -- Chỉ dùng cho các bậc chiết khấu số lượng
    is_active          boolean       NOT NULL DEFAULT true
);

-- Mỗi (mã, phương thức, nước đến) chỉ có một dòng, kể cả khi phương thức / nước đến để trống
CREATE UNIQUE INDEX uq_price_items
    ON pricing.price_items (item_code, coalesce(transport_mode, ''), coalesce(dest_country_code, ''));

-- =====================================================================================
-- 11. BILLING (R-02)
-- =====================================================================================

-- Mỗi lần thu / hoàn tiền là một dòng. Số tiền gốc tính USD (như báo giá); VNPay chỉ nhận VND nên lưu
-- kèm số VND và tỉ giá tại thời điểm tạo giao dịch.
--   payment_type: Deposit (cọc) | Balance (phần còn lại của giá báo) | Extra (chi phí phát sinh) | Refund (hoàn tiền)
--   provider    : VnPay | Mock (cổng giả lập khi chưa có key) | Manual (Manager ghi nhận tiền nhận ngoài hệ thống)
--   status      : Pending -> Succeeded | Failed | Expired
CREATE TABLE billing.payments (
    payment_id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_code           varchar(30)   NOT NULL CONSTRAINT uq_payments_code UNIQUE, -- PAY-2026-0001
    booking_id             integer       NOT NULL REFERENCES booking.booking_requests (booking_id),
    payment_type           varchar(10)   NOT NULL
        CONSTRAINT ck_payments_type CHECK (payment_type IN ('Deposit', 'Balance', 'Extra', 'Refund')),
    provider               varchar(10)   NOT NULL
        CONSTRAINT ck_payments_provider CHECK (provider IN ('VnPay', 'Mock', 'Manual')),
    status                 varchar(10)   NOT NULL DEFAULT 'Pending'
        CONSTRAINT ck_payments_status CHECK (status IN ('Pending', 'Succeeded', 'Failed', 'Expired')),
    amount                 numeric(18,2) NOT NULL CONSTRAINT ck_payments_amount CHECK (amount > 0),
    currency_code          char(3)       NOT NULL DEFAULT 'USD',
    exchange_rate          numeric(18,4) NOT NULL,                 -- VND cho 1 đơn vị currency_code
    amount_vnd             bigint        NOT NULL,
    txn_ref                varchar(40)   NOT NULL CONSTRAINT uq_payments_txn_ref UNIQUE, -- mã gửi cổng thanh toán (vnp_TxnRef)
    provider_txn_no        varchar(50),                            -- mã giao dịch phía VNPay (vnp_TransactionNo)
    provider_pay_date      varchar(14),                            -- vnp_PayDate (yyyyMMddHHmmss, giờ VN), cần khi hoàn tiền
    bank_code              varchar(20),
    response_code          varchar(10),
    refund_of_payment_id   integer REFERENCES billing.payments (payment_id), -- dòng Refund trỏ về giao dịch gốc
    note                   varchar(500),
    created_by_user_id     integer REFERENCES identity.users (user_id),
    created_at             timestamptz   NOT NULL DEFAULT now(),
    paid_at                timestamptz,
    raw_response           jsonb,
    CONSTRAINT ck_payments_refund_link CHECK ((payment_type = 'Refund') = (refund_of_payment_id IS NOT NULL))
);

CREATE INDEX ix_payments_booking ON billing.payments (booking_id, created_at DESC);
