-- SCRIPT 01: SCHEMA (11 schema, 23 bảng)
-- System: Cross-Border Racehorse Transport System (SWP391 - Group 5)
-- Target DBMS: PostgreSQL 15+ / Supabase
-- Chuyển từ bản SQL Server (Assessment 3, script 01-04 v3). Khác biệt so với bản cũ:
--   * Tên schema/bảng/cột theo chuẩn PostgreSQL: snake_case, chữ thường.
--   * Schema "auth" đổi thành "identity" vì Supabase đã dùng tên "auth" cho hệ thống riêng.
--   * Không còn stored procedure: tính báo giá và chốt KPI nằm ở tầng Services (C#).
--   * Thời gian lưu kiểu timestamptz (UTC).
-- Chạy trong database đã chọn sẵn (local: racehorse_transport, Supabase: postgres).
-- =====================================================================================

CREATE SCHEMA identity;   -- Tài khoản: khách hàng và nhân sự
CREATE SCHEMA racehorse;  -- Hồ sơ ngựa đua
CREATE SCHEMA booking;    -- Yêu cầu vận chuyển (Flow 1)
CREATE SCHEMA clearance;  -- Hồ sơ pháp lý, kiểm dịch, thông quan (Flow 2)
CREATE SCHEMA fleet;      -- Phương tiện, chuyến đi, lộ trình (Flow 3)
CREATE SCHEMA tracking;   -- Nhật ký thể trạng ngựa (Flow 4)
CREATE SCHEMA incident;   -- Sự cố và nắn tuyến (Flow 5)
CREATE SCHEMA acceptance; -- Bàn giao e-POD (Flow 6)
CREATE SCHEMA common;     -- Thông báo
CREATE SCHEMA pricing;    -- Bảng giá
CREATE SCHEMA billing;    -- Thanh toán: đặt cọc, phần còn lại, phát sinh, hoàn tiền

-- =====================================================================================
-- 1. IDENTITY
-- =====================================================================================

-- Bảng 1: Tài khoản (gộp khách hàng và nhân sự, phân biệt bằng role)
CREATE TABLE identity.users (
    user_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name      varchar(100) NOT NULL,
    email          varchar(100) NOT NULL CONSTRAINT uq_users_email UNIQUE, -- luôn lưu chữ thường
    password_hash  varchar(255) NOT NULL,
    phone_number   varchar(30),
    role           varchar(30)  NOT NULL DEFAULT 'Customer'
        CONSTRAINT ck_users_role CHECK (role IN ('Customer', 'LogisticsManager', 'TransportSpecialist', 'FleetCoordinator', 'DriverEscort', 'Admin')),
    is_active      boolean      NOT NULL DEFAULT true,
    created_at     timestamptz  NOT NULL DEFAULT now()
);

-- Token dùng một lần, có hạn: refresh token, đặt lại mật khẩu. Chỉ lưu mã băm.
CREATE TABLE identity.user_tokens (
    token_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     integer      NOT NULL REFERENCES identity.users (user_id) ON DELETE CASCADE,
    token_type  varchar(30)  NOT NULL
        CONSTRAINT ck_user_tokens_type CHECK (token_type IN ('Refresh', 'PasswordReset')),
    token_hash  varchar(128) NOT NULL CONSTRAINT uq_user_tokens_hash UNIQUE,
    expires_at  timestamptz  NOT NULL,
    used_at     timestamptz,
    created_at  timestamptz  NOT NULL DEFAULT now()
);

CREATE INDEX ix_user_tokens_user ON identity.user_tokens (user_id, token_type);

-- =====================================================================================
-- 2. RACEHORSE
-- =====================================================================================

-- Bảng 2: Hồ sơ cá thể ngựa
CREATE TABLE racehorse.horses (
    horse_id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id              integer      NOT NULL REFERENCES identity.users (user_id),
    name                       varchar(100) NOT NULL,
    microchip_number           varchar(30)  NOT NULL CONSTRAINT uq_horses_microchip UNIQUE, -- Mã RFID ISO
    passport_number            varchar(50)  NOT NULL CONSTRAINT uq_horses_passport UNIQUE,  -- Hộ chiếu FEI
    breed                      varchar(50)  NOT NULL DEFAULT 'Thoroughbred',
    gender                     varchar(10)  NOT NULL
        CONSTRAINT ck_horses_gender CHECK (gender IN ('Stallion', 'Mare', 'Gelding')),
    date_of_birth              date         NOT NULL,
    color                      varchar(30)  NOT NULL,
    special_care_requirements  text,        -- Dinh dưỡng, đệm chuồng, tiền sử say xe
    photo_url                  varchar(500),
    is_active                  boolean      NOT NULL DEFAULT true,
    created_at                 timestamptz  NOT NULL DEFAULT now()
);

-- =====================================================================================
-- 3. BOOKING (Flow 1)
-- =====================================================================================

-- Bảng 3: Yêu cầu đặt chuyến
CREATE TABLE booking.booking_requests (
    booking_id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_code             varchar(30)   NOT NULL CONSTRAINT uq_booking_requests_code UNIQUE,
    customer_user_id         integer       NOT NULL REFERENCES identity.users (user_id),
    pickup_address           varchar(255)  NOT NULL,
    pickup_country_code      char(2)       NOT NULL,
    pickup_lat               numeric(9,6),
    pickup_lng               numeric(9,6),
    dropoff_address          varchar(255)  NOT NULL,
    dropoff_country_code     char(2)       NOT NULL,
    dropoff_lat              numeric(9,6),
    dropoff_lng              numeric(9,6),
    -- Khách không chọn ngày chạy: chỉ cho biết ngựa sẵn sàng được đón trong khoảng nào và hạn giao trễ nhất.
    -- Ngày chạy thật do Coordinator chốt khi lập chuyến (fleet.trips.planned_start_date).
    pickup_window_start      timestamptz   NOT NULL,
    pickup_window_end        timestamptz   NOT NULL,
    delivery_deadline        timestamptz   NOT NULL,
    total_horses             integer       NOT NULL CONSTRAINT ck_booking_requests_total CHECK (total_horses > 0),
    special_instructions     text,
    estimated_cost           numeric(18,2) NOT NULL DEFAULT 0,
    currency_code            char(3)       NOT NULL DEFAULT 'USD',
    -- Vòng đời: Submitted -> AwaitingDeposit (Manager duyệt, chờ cọc) -> Approved (đã cọc: làm hồ sơ, xếp chuyến)
    --           -> Completed, hoặc -> AwaitingFinalPayment (còn chi phí phát sinh) -> Completed
    --           | Rejected | Expired (quá hạn duyệt / quá hạn cọc) | Cancelled. 'Assigned' là trạng thái cũ, không còn dùng.
    status                   varchar(25)   NOT NULL DEFAULT 'Submitted'
        CONSTRAINT ck_booking_requests_status CHECK (status IN ('Submitted', 'AwaitingDeposit', 'Approved', 'Assigned', 'AwaitingFinalPayment', 'Completed', 'Rejected', 'Expired', 'Cancelled')),
    rejection_reason         varchar(500),
    reviewed_by_user_id      integer REFERENCES identity.users (user_id),
    reviewed_at              timestamptz,
    assigned_specialist_id   integer REFERENCES identity.users (user_id), -- Chuyên viên phụ trách hồ sơ kiểm dịch
    assigned_coordinator_id  integer REFERENCES identity.users (user_id), -- Điều phối viên phụ trách lộ trình/xe
    created_at               timestamptz   NOT NULL DEFAULT now(),
    -- Đầu vào của công thức tính giá
    transport_mode           varchar(10)   NOT NULL DEFAULT 'Ground'
        CONSTRAINT ck_booking_requests_mode CHECK (transport_mode IN ('Ground', 'Air')),
    distance_km              integer CONSTRAINT ck_booking_requests_distance CHECK (distance_km > 0),
    is_express               boolean       NOT NULL DEFAULT false,
    requires_climate_control boolean       NOT NULL DEFAULT false,
    declared_value           numeric(18,2), -- NULL = khách không mua bảo hiểm
    quote_breakdown          jsonb,         -- Chi tiết các dòng báo giá
    estimated_transit_hours  numeric(7,1),  -- Thời gian vận chuyển hệ thống ước tính lúc báo giá
    -- Thanh toán (R-02). % cọc chụp lại lúc Manager duyệt để đổi cấu hình không ảnh hưởng đơn cũ.
    deposit_percent          numeric(5,2),
    deposit_amount           numeric(18,2) NOT NULL DEFAULT 0,
    extra_charges            numeric(18,2) NOT NULL DEFAULT 0, -- chi phí phát sinh (sự cố) chốt khi đóng chuyến
    extra_due_at             timestamptz,                      -- hạn trả phần phát sinh
    payment_reminder_count   integer       NOT NULL DEFAULT 0, -- số lần đã nhắc nợ phần phát sinh
    CONSTRAINT ck_booking_requests_dates CHECK (pickup_window_end >= pickup_window_start AND delivery_deadline > pickup_window_start)
);

-- Bảng 4: Ngựa trong đơn (nhiều - nhiều giữa đơn và ngựa)
CREATE TABLE booking.booking_horses (
    booking_horse_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id        integer     NOT NULL REFERENCES booking.booking_requests (booking_id),
    horse_id          integer     NOT NULL REFERENCES racehorse.horses (horse_id),
    notes             varchar(300),
    status            varchar(20) NOT NULL DEFAULT 'Pending'
        CONSTRAINT ck_booking_horses_status CHECK (status IN ('Pending', 'Approved', 'Cancelled', 'Deceased')), -- Deceased: chết trên đường (R-12)
    stall_class       varchar(10) NOT NULL DEFAULT 'Shared' -- Hạng chuồng (hệ số nhân cước)
        CONSTRAINT ck_booking_horses_stall CHECK (stall_class IN ('Shared', 'Comfort', 'Private')),
    CONSTRAINT uq_booking_horses UNIQUE (booking_id, horse_id)
);

-- Nước quá cảnh của đơn (ngựa đi qua, thường là đường bộ), theo thứ tự từ nước đi tới nước đến.
-- Đường bay thẳng thì không có dòng nào. Hồ sơ kiểm dịch phải có thêm giấy tờ "Transit" của từng nước này.
CREATE TABLE booking.booking_transit_countries (
    booking_id      integer NOT NULL REFERENCES booking.booking_requests (booking_id),
    sequence_order  integer NOT NULL CONSTRAINT ck_booking_transit_countries_seq CHECK (sequence_order > 0),
    country_code    char(2) NOT NULL,
    CONSTRAINT pk_booking_transit_countries PRIMARY KEY (booking_id, sequence_order),
    CONSTRAINT uq_booking_transit_countries UNIQUE (booking_id, country_code)
);

-- =====================================================================================
-- 4. CLEARANCE (Flow 2)
-- =====================================================================================

-- Bảng 5: Danh mục loại giấy tờ
CREATE TABLE clearance.document_types (
    doc_type_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          varchar(30)  NOT NULL CONSTRAINT uq_document_types_code UNIQUE,
    name          varchar(100) NOT NULL,
    description   varchar(255),
    is_mandatory  boolean      NOT NULL DEFAULT true
);

-- Hồ sơ thú y lưu theo từng con ngựa (hộ chiếu, xét nghiệm, tiêm phòng...), chủ ngựa bổ sung bất cứ lúc nào.
-- Khác clearance.dossier_documents: bảng đó là giấy tờ nộp cho từng đơn và được Specialist duyệt.
CREATE TABLE racehorse.horse_documents (
    document_id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    horse_id             integer      NOT NULL REFERENCES racehorse.horses (horse_id),
    doc_type_id          integer      NOT NULL REFERENCES clearance.document_types (doc_type_id),
    document_number      varchar(100),
    issued_by            varchar(200), -- Bác sĩ thú y / phòng xét nghiệm / cơ quan cấp
    issue_date           date,
    expiry_date          date,
    file_url             varchar(500) NOT NULL,
    notes                varchar(500),
    uploaded_by_user_id  integer      NOT NULL REFERENCES identity.users (user_id),
    uploaded_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_horse_documents_dates CHECK (expiry_date IS NULL OR issue_date IS NULL OR expiry_date >= issue_date)
);

CREATE INDEX ix_horse_documents_horse ON racehorse.horse_documents (horse_id);

-- Bảng 6: Quy định giấy tờ bắt buộc theo từng quốc gia
CREATE TABLE clearance.country_doc_requirements (
    requirement_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_code     char(2)     NOT NULL,
    direction        varchar(10) NOT NULL
        CONSTRAINT ck_country_doc_requirements_direction CHECK (direction IN ('Export', 'Import', 'Transit')),
    doc_type_id      integer     NOT NULL REFERENCES clearance.document_types (doc_type_id),
    validity_days    integer,    -- Giấy phải được cấp trong vòng N ngày trước ngày đi
    processing_days  integer CONSTRAINT ck_country_doc_requirements_processing CHECK (processing_days >= 0),
                                 -- Số ngày cần để có giấy (xin phép, xét nghiệm, cách ly); dùng tính ngày pickup sớm nhất
    is_mandatory     boolean     NOT NULL DEFAULT true,
    regulation_note  varchar(255),
    CONSTRAINT uq_country_doc_requirements UNIQUE (country_code, direction, doc_type_id)
);

-- Bảng 7: Bộ hồ sơ số hóa cho từng con ngựa trong đơn (1 - 1 với booking_horses)
CREATE TABLE clearance.digital_dossiers (
    dossier_id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dossier_code        varchar(30) NOT NULL CONSTRAINT uq_digital_dossiers_code UNIQUE,
    booking_horse_id    integer     NOT NULL CONSTRAINT uq_digital_dossiers_booking_horse UNIQUE
        REFERENCES booking.booking_horses (booking_horse_id),
    specialist_user_id  integer     NOT NULL REFERENCES identity.users (user_id),
    status              varchar(30) NOT NULL DEFAULT 'Draft'
        CONSTRAINT ck_digital_dossiers_status CHECK (status IN ('Draft', 'AwaitingDocs', 'Reviewing', 'SubmittedToAuthorities', 'Cleared', 'Issue')),
    clearance_number    varchar(50),
    issue_reason        text,
    cleared_at          timestamptz,
    created_at          timestamptz NOT NULL DEFAULT now()
);

-- Bảng 8: Giấy tờ đính kèm hồ sơ
CREATE TABLE clearance.dossier_documents (
    document_id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dossier_id           integer      NOT NULL REFERENCES clearance.digital_dossiers (dossier_id),
    doc_type_id          integer      NOT NULL REFERENCES clearance.document_types (doc_type_id),
    document_number      varchar(100),
    file_url             varchar(500) NOT NULL,
    uploaded_by_user_id  integer      NOT NULL REFERENCES identity.users (user_id),
    uploaded_at          timestamptz  NOT NULL DEFAULT now(),
    status               varchar(20)  NOT NULL DEFAULT 'Pending'
        CONSTRAINT ck_dossier_documents_status CHECK (status IN ('Pending', 'Approved', 'Rejected')),
    correction_note      varchar(500),
    reviewed_by_user_id  integer REFERENCES identity.users (user_id),
    reviewed_at          timestamptz,
    expiry_date          date,
    rejection_count      integer      NOT NULL DEFAULT 0 -- Khách được nộp lại tối đa 3 lần
        CONSTRAINT ck_dossier_documents_rejection_count CHECK (rejection_count BETWEEN 0 AND 3)
);

-- =====================================================================================
-- 5. FLEET (Flow 3)
-- =====================================================================================

-- Bảng 9: Phương tiện chuyên dụng (xe thùng, khoang bay)
CREATE TABLE fleet.transport_assets (
    asset_id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_code              varchar(30) NOT NULL CONSTRAINT uq_transport_assets_code UNIQUE, -- Biển số / mã khoang
    asset_type              varchar(30) NOT NULL DEFAULT 'HorseTruck_AirSuspension'
        CONSTRAINT ck_transport_assets_type CHECK (asset_type IN ('HorseTruck_AirSuspension', 'HorseVan', 'AirStall')),
    capacity_horses         integer     NOT NULL
        CONSTRAINT ck_transport_assets_capacity CHECK (capacity_horses BETWEEN 1 AND 12),
    has_climate_control     boolean     NOT NULL DEFAULT true,
    has_gps_tracker         boolean     NOT NULL DEFAULT true,
    status                  varchar(20) NOT NULL DEFAULT 'Available'
        CONSTRAINT ck_transport_assets_status CHECK (status IN ('Available', 'InTransit', 'Maintenance')),
    last_sanitization_date  timestamptz
);

-- Bảng 10: Chuyến đi (gồm cả kế hoạch và quyết toán KPI khi đóng chuyến)
-- Quan hệ Đơn - Chuyến là nhiều - nhiều qua trip_horses; nhân sự của chuyến nằm ở trip_crew.
CREATE TABLE fleet.trips (
    trip_id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_code              varchar(30)   NOT NULL CONSTRAINT uq_trips_code UNIQUE,
    vehicle_id             integer       NOT NULL REFERENCES fleet.transport_assets (asset_id),
    planned_start_date     timestamptz   NOT NULL,
    planned_end_date       timestamptz   NOT NULL,
    actual_start_date      timestamptz,
    actual_end_date        timestamptz,
    planned_cost           numeric(18,2) NOT NULL DEFAULT 0,
    actual_cost            numeric(18,2) NOT NULL DEFAULT 0,
    -- Vòng đời: Draft -> PendingApproval -> Scheduled -> InTransit <-> EmergencyRerouting -> ArrivedDestination -> Completed | Cancelled
    overall_status         varchar(25)   NOT NULL DEFAULT 'Draft'
        CONSTRAINT ck_trips_status CHECK (overall_status IN ('Draft', 'PendingApproval', 'Scheduled', 'InTransit', 'EmergencyRerouting', 'ArrivedDestination', 'Completed', 'Cancelled')),
    -- Quyết toán khi đóng chuyến (Flow 6)
    delay_minutes          integer       NOT NULL DEFAULT 0,
    on_time_status         varchar(30)   NOT NULL DEFAULT 'OnTime',
    kpi_score              numeric(5,2)  NOT NULL DEFAULT 100,
    closed_by_user_id      integer REFERENCES identity.users (user_id),
    closed_at              timestamptz,
    executive_remarks      text,
    created_at             timestamptz   NOT NULL DEFAULT now(),
    -- Duyệt kế hoạch (Flow 3)
    planned_by_user_id     integer REFERENCES identity.users (user_id), -- Coordinator lập kế hoạch
    approved_by_user_id    integer REFERENCES identity.users (user_id), -- Manager duyệt kế hoạch
    approved_at            timestamptz,
    plan_rejection_count   integer       NOT NULL DEFAULT 0
        CONSTRAINT ck_trips_plan_rejection_count CHECK (plan_rejection_count BETWEEN 0 AND 3),
    plan_rejection_reason  varchar(500),
    CONSTRAINT ck_trips_dates CHECK (planned_end_date > planned_start_date)
);

-- Bảng 11: Nhân sự của chuyến (nhiều tài xế thay ca, 1 người áp tải cho mỗi 3 ngựa)
CREATE TABLE fleet.trip_crew (
    trip_crew_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id       integer     NOT NULL REFERENCES fleet.trips (trip_id),
    user_id       integer     NOT NULL REFERENCES identity.users (user_id),
    crew_role     varchar(10) NOT NULL
        CONSTRAINT ck_trip_crew_role CHECK (crew_role IN ('Driver', 'Escort')),
    is_lead       boolean     NOT NULL DEFAULT false, -- Tài xế chính / trưởng nhóm áp tải
    duty          varchar(200),
    CONSTRAINT uq_trip_crew UNIQUE (trip_id, user_id, crew_role)
);

-- Bảng 12: Ngựa trên chuyến và vị trí chuồng
CREATE TABLE fleet.trip_horses (
    trip_horse_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id            integer NOT NULL REFERENCES fleet.trips (trip_id),
    booking_horse_id   integer NOT NULL REFERENCES booking.booking_horses (booking_horse_id),
    stall_slot_number  integer NOT NULL,
    notes              varchar(200),
    escort_user_id     integer REFERENCES identity.users (user_id), -- Escort phụ trách con này (R-06), tối đa 3 con / escort
    -- Trạng thái riêng của từng con trên chuyến (R-05); trạng thái chuyến là trạng thái của xe
    status             varchar(20) NOT NULL DEFAULT 'Planned'
        CONSTRAINT ck_trip_horses_status CHECK (status IN ('Planned', 'InTransit', 'Delivered', 'Offloaded', 'Deceased', 'Cancelled')),
    picked_up_at       timestamptz,   -- lúc xe rời điểm đón của con ngựa
    delivered_at       timestamptz,   -- lúc ký biên bản bàn giao
    handover_id        integer,       -- biên bản e-POD (khóa ngoại thêm sau khi tạo bảng handover_acceptances)
    offloaded_at       timestamptz,   -- rời chuyến giữa đường, chỉ qua sự cố (R-12)
    offload_reason     varchar(300),
    -- Hướng xử lý tiếp khi rời chuyến; NULL = tài xế dỡ khẩn cấp, chờ phương án được duyệt.
    -- Chỉ WaitRecover đưa con ngựa về hàng chờ xếp chuyến.
    offload_outcome    varchar(20)
        CONSTRAINT ck_trip_horses_offload_outcome CHECK (offload_outcome IN ('WaitRecover', 'ReturnToOrigin', 'HandOverHere', 'Deceased')),
    CONSTRAINT uq_trip_horses UNIQUE (trip_id, booking_horse_id),
    CONSTRAINT uq_trip_horses_stall UNIQUE (trip_id, stall_slot_number) -- Hai ngựa không chung một ô chuồng
);

-- Bảng 13: Mốc lộ trình (kèm giờ check-in thực tế)
CREATE TABLE fleet.route_checkpoints (
    checkpoint_id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id                 integer      NOT NULL REFERENCES fleet.trips (trip_id),
    sequence_order          integer      NOT NULL,
    checkpoint_name         varchar(100) NOT NULL,
    checkpoint_type         varchar(30)  NOT NULL
        CONSTRAINT ck_route_checkpoints_type CHECK (checkpoint_type IN ('Origin', 'PickUp', 'RestStop', 'BorderGate', 'DropOff', 'Destination')),
    address                 varchar(255) NOT NULL,
    latitude                numeric(9,6),
    longitude               numeric(9,6),
    distance_km_from_previous numeric(10,2),
    planned_time            timestamptz  NOT NULL,
    mandatory_rest_minutes  integer      NOT NULL DEFAULT 0,
    actual_arrival_time     timestamptz,
    actual_departure_time   timestamptz,
    status                  varchar(20)  NOT NULL DEFAULT 'Pending'
        CONSTRAINT ck_route_checkpoints_status CHECK (status IN ('Pending', 'Arrived', 'Cleared', 'Departed', 'Cancelled')),
    is_active               boolean      NOT NULL DEFAULT true, -- false = mốc đã bị nắn tuyến
    -- Mốc PickUp / DropOff là nơi đón / trả ngựa của một đơn (R-04, ghép nhiều đơn vào một chuyến).
    -- Đơn không có PickUp thì lên xe ở mốc Origin; không có DropOff thì giao ở mốc Destination.
    booking_id              integer REFERENCES booking.booking_requests (booking_id),
    CONSTRAINT ck_route_checkpoints_booking CHECK ((checkpoint_type IN ('PickUp', 'DropOff')) = (booking_id IS NOT NULL))
);

-- Thứ tự mốc không trùng trong các mốc còn hiệu lực
CREATE UNIQUE INDEX uq_route_checkpoints_sequence
    ON fleet.route_checkpoints (trip_id, sequence_order) WHERE is_active;

