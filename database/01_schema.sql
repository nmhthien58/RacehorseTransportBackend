-- 11. BILLING (R-02)
-- =====================================================================================

-- Mỗi lần thu / hoàn tiền là một dòng. Số tiền gốc tính USD (như báo giá); VNPay chỉ nhận VND nên lưu
-- kèm số VND và tỉ giá tại thời điểm tạo giao dịch.
--   payment_type: Deposit (cọc) | Balance (phần còn lại của giá báo) | Extra (chi phí phát sinh) | Refund (hoàn tiền) | Compensation (bồi thường bảo hiểm)
--   provider    : VnPay | Mock (cổng giả lập khi chưa có key) | Manual (Manager ghi nhận tiền nhận ngoài hệ thống)
--   status      : Pending -> Succeeded | Failed | Expired
CREATE TABLE billing.payments (
    payment_id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_code           varchar(30)   NOT NULL CONSTRAINT uq_payments_code UNIQUE, -- PAY-2026-0001
    booking_id             integer       NOT NULL REFERENCES booking.booking_requests (booking_id),
    payment_type           varchar(15)   NOT NULL
        CONSTRAINT ck_payments_type CHECK (payment_type IN ('Deposit', 'Balance', 'Extra', 'Refund', 'Compensation')),
    provider               varchar(10)   NOT NULL
        CONSTRAINT ck_payments_provider CHECK (provider IN ('VnPay', 'Mock', 'Manual')),
    status                 varchar(10)   NOT NULL DEFAULT 'Pending'
        CONSTRAINT ck_payments_status CHECK (status IN ('Pending', 'Succeeded', 'Failed', 'Expired')),
    amount                 numeric(18,2) NOT NULL CONSTRAINT ck_payments_amount CHECK (amount > 0),
    currency_code          char(3)       NOT NULL DEFAULT 'USD',
    exchange_rate          numeric(18,4) NOT NULL,                 -- VND cho 1 đơn vị currency_code
    amount_vnd             bigint        NOT NULL,
    txn_ref                varchar(40)   NOT NULL CONSTRAINT uq_payments_txn_ref UNIQUE, -- mã gửi cổng thanh toán (vnp_TxnRef)
    provider_txn_no        varchar(50),                            -- mã giao dịch phía VNPay (vnp_TransactionNo)
    provider_pay_date      varchar(14),                            -- vnp_PayDate (yyyyMMddHHmmss, giờ VN), cần khi hoàn tiền
    bank_code              varchar(20),
    response_code          varchar(10),
    refund_of_payment_id   integer REFERENCES billing.payments (payment_id), -- dòng Refund trỏ về giao dịch gốc
    note                   varchar(500),
    created_by_user_id     integer REFERENCES identity.users (user_id),
    created_at             timestamptz   NOT NULL DEFAULT now(),
    paid_at                timestamptz,
    raw_response           jsonb,
    CONSTRAINT ck_payments_refund_link CHECK ((payment_type = 'Refund' AND refund_of_payment_id IS NOT NULL)
        OR payment_type = 'Compensation'
        OR (payment_type NOT IN ('Refund', 'Compensation') AND refund_of_payment_id IS NULL))
);

-- Bồi thường giao trễ (R-09): tính khi đóng chuyến cho từng đơn giao trễ do lỗi công ty; Manager duyệt / sửa / từ chối.
-- Duyệt xong, tiền được hoàn qua các dòng Refund của billing.payments.
CREATE TABLE billing.delay_compensations (
    delay_compensation_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id             integer       NOT NULL REFERENCES booking.booking_requests (booking_id),
    trip_id                integer       NOT NULL REFERENCES fleet.trips (trip_id),
    delay_hours            numeric(10,2) NOT NULL,
    freight_amount         numeric(18,2) NOT NULL,  -- báo giá - bảo hiểm - phí thủ tục
    percent                numeric(5,2)  NOT NULL,
    calculated_amount      numeric(18,2) NOT NULL CONSTRAINT ck_delay_compensations_calculated CHECK (calculated_amount >= 0),
    approved_amount        numeric(18,2) CONSTRAINT ck_delay_compensations_approved CHECK (approved_amount >= 0),
    currency_code          char(3)       NOT NULL DEFAULT 'USD',
    status                 varchar(20)   NOT NULL DEFAULT 'AwaitingApproval'
        CONSTRAINT ck_delay_compensations_status CHECK (status IN ('AwaitingApproval', 'Approved', 'Rejected')),
    review_reason          varchar(500),
    reviewed_by_user_id    integer REFERENCES identity.users (user_id),
    reviewed_at            timestamptz,
    created_at             timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT uq_delay_compensations_booking_trip UNIQUE (booking_id, trip_id)
);

CREATE INDEX ix_payments_booking ON billing.payments (booking_id, created_at DESC);
