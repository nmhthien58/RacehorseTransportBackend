-- 6. TRACKING (Flow 4)
-- =====================================================================================

-- Bảng 14: Nhật ký thể trạng ngựa
CREATE TABLE tracking.horse_welfare_logs (
    log_id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_horse_id        integer      NOT NULL REFERENCES fleet.trip_horses (trip_horse_id),
    checkpoint_id        integer REFERENCES fleet.route_checkpoints (checkpoint_id),
    recorded_by_user_id  integer      NOT NULL REFERENCES identity.users (user_id),
    cabin_temp           numeric(4,1) NOT NULL,
    water_intake_liters  numeric(4,1) NOT NULL,
    feed_status          varchar(20)  NOT NULL
        CONSTRAINT ck_horse_welfare_logs_feed CHECK (feed_status IN ('Normal', 'Reduced', 'Refused')),
    stress_level         varchar(20)  NOT NULL
        CONSTRAINT ck_horse_welfare_logs_stress CHECK (stress_level IN ('Calm', 'MildStress', 'Agitated')),
    notes                text,
    photo_url            varchar(500),
    logged_at            timestamptz  NOT NULL DEFAULT now()
);

