ALTER TABLE identity.users
    ADD COLUMN IF NOT EXISTS email_verified_at timestamptz;

-- Tài khoản đã có từ trước coi như đã xác thực, để không ai bị chặn sau khi cập nhật
UPDATE identity.users
SET email_verified_at = created_at
WHERE email_verified_at IS NULL;

CREATE TABLE IF NOT EXISTS identity.user_tokens (
    token_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     integer      NOT NULL REFERENCES identity.users (user_id) ON DELETE CASCADE,
    token_type  varchar(30)  NOT NULL
        CONSTRAINT ck_user_tokens_type CHECK (token_type IN ('Refresh', 'EmailVerification', 'PasswordReset')),
    token_hash  varchar(128) NOT NULL CONSTRAINT uq_user_tokens_hash UNIQUE,
    expires_at  timestamptz  NOT NULL,
    used_at     timestamptz,
    created_at  timestamptz  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_user_tokens_user ON identity.user_tokens (user_id, token_type);
