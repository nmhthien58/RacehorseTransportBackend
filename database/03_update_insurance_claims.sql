-- 'Compensation' dài 12 ký tự: nới cột; bồi thường qua cổng thanh toán gắn khoản gốc, chuyển khoản thủ công thì không
ALTER TABLE billing.payments ALTER COLUMN payment_type TYPE varchar(15);
ALTER TABLE billing.payments DROP CONSTRAINT IF EXISTS ck_payments_refund_link;
ALTER TABLE billing.payments ADD CONSTRAINT ck_payments_refund_link CHECK ((payment_type = 'Refund' AND refund_of_payment_id IS NOT NULL)
        OR payment_type = 'Compensation'
        OR (payment_type NOT IN ('Refund', 'Compensation') AND refund_of_payment_id IS NULL));
ALTER TABLE billing.payments DROP CONSTRAINT IF EXISTS ck_payments_type;
ALTER TABLE billing.payments ADD CONSTRAINT ck_payments_type CHECK (payment_type IN ('Deposit', 'Balance', 'Extra', 'Refund', 'Compensation'));

CREATE TABLE IF NOT EXISTS billing.insurance_claims (
    claim_id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_code            varchar(20)   NOT NULL UNIQUE,
    booking_id            integer       NOT NULL REFERENCES booking.booking_requests (booking_id),
    booking_horse_id      integer       NOT NULL REFERENCES booking.booking_horses (booking_horse_id),
    incident_id           integer REFERENCES incident.trip_incidents (incident_id),
    delivery_failure_id   integer REFERENCES acceptance.delivery_failures (failure_id),
    claim_type            varchar(10)   NOT NULL
        CONSTRAINT ck_insurance_claims_type CHECK (claim_type IN ('Death', 'Injury', 'Loss')),
    insurance_plan        varchar(10)   NOT NULL
        CONSTRAINT ck_insurance_claims_plan CHECK (insurance_plan IN ('None', 'Full')),
    agreed_value          numeric(18,2),
    fault_party           varchar(15)
        CONSTRAINT ck_insurance_claims_fault_party CHECK (fault_party IN ('Company', 'Customer', 'ForceMajeure')),
    description           varchar(2000) NOT NULL,
    requested_amount      numeric(18,2) CONSTRAINT ck_insurance_claims_requested CHECK (requested_amount IS NULL OR requested_amount >= 0),
    approved_amount       numeric(18,2) CONSTRAINT ck_insurance_claims_approved CHECK (approved_amount IS NULL OR approved_amount >= 0),
    status                varchar(15)   NOT NULL DEFAULT 'Open'
        CONSTRAINT ck_insurance_claims_status CHECK (status IN ('Open', 'UnderReview', 'Approved', 'Rejected', 'Paid')),
    decision_reason       varchar(1000),
    evidence_paths        jsonb         NOT NULL DEFAULT '[]',
    opened_by_user_id     integer REFERENCES identity.users (user_id),
    opened_at             timestamptz   NOT NULL DEFAULT now(),
    reviewed_by_user_id   integer REFERENCES identity.users (user_id),
    reviewed_at           timestamptz,
    paid_at               timestamptz,
    paid_reference        varchar(100)
);
