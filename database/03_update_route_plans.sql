ALTER TABLE booking.booking_requests DROP CONSTRAINT IF EXISTS ck_booking_requests_status;
ALTER TABLE booking.booking_requests
    ADD CONSTRAINT ck_booking_requests_status CHECK (status IN ('Submitted', 'PreApproved', 'RoutePlanned', 'AwaitingDeposit', 'Approved', 'Assigned', 'AwaitingFinalPayment', 'Completed', 'Rejected', 'Expired', 'Cancelled'));

CREATE TABLE IF NOT EXISTS booking.route_plans (
    route_plan_id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id             integer       NOT NULL REFERENCES booking.booking_requests (booking_id),
    version                integer       NOT NULL,
    status                 varchar(15)   NOT NULL DEFAULT 'Draft'
        CONSTRAINT ck_route_plans_status CHECK (status IN ('Draft', 'Submitted', 'Approved', 'Rejected', 'Superseded')),
    transit_country_codes  jsonb         NOT NULL DEFAULT '[]',
    total_distance_km      numeric(10,2) NOT NULL,
    estimated_hours        numeric(8,2)  NOT NULL,
    is_estimate            boolean       NOT NULL DEFAULT false, -- có chặng ước tính theo đường chim bay
    polyline               jsonb,                                -- [[lat, lng], ...] đã rút gọn để vẽ
    notes                  varchar(1000),
    planned_by_user_id     integer       NOT NULL REFERENCES identity.users (user_id),
    reviewed_by_user_id    integer REFERENCES identity.users (user_id),
    reviewed_at            timestamptz,
    rejection_reason       varchar(500),
    created_at             timestamptz   NOT NULL DEFAULT now(),
    updated_at             timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT uq_route_plans_booking_version UNIQUE (booking_id, version)
);

-- Mỗi đơn chỉ một tuyến Approved hiệu lực
CREATE UNIQUE INDEX IF NOT EXISTS uq_route_plans_one_approved ON booking.route_plans (booking_id) WHERE status = 'Approved';

CREATE TABLE IF NOT EXISTS booking.route_plan_stops (
    route_plan_stop_id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_plan_id                  integer       NOT NULL REFERENCES booking.route_plans (route_plan_id) ON DELETE CASCADE,
    sequence_order                 integer       NOT NULL,
    stop_name                      varchar(100)  NOT NULL,
    stop_type                      varchar(15)   NOT NULL
        CONSTRAINT ck_route_plan_stops_type CHECK (stop_type IN ('Origin', 'RestStop', 'BorderGate', 'Destination')),
    address                        varchar(255)  NOT NULL,
    latitude                       numeric(9,6)  NOT NULL,
    longitude                      numeric(9,6)  NOT NULL,
    country_code                   char(2),
    distance_km_from_previous      numeric(10,2),
    duration_hours_from_previous   numeric(8,2),
    rest_minutes                   integer       NOT NULL DEFAULT 0 CONSTRAINT ck_route_plan_stops_rest CHECK (rest_minutes >= 0),
    CONSTRAINT uq_route_plan_stops_order UNIQUE (route_plan_id, sequence_order)
);
