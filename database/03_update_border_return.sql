ALTER TABLE incident.trip_incidents
    ADD COLUMN IF NOT EXISTS extra_cost_for_customer numeric(18,2) NOT NULL DEFAULT 0;
ALTER TABLE incident.trip_incidents DROP CONSTRAINT IF EXISTS ck_trip_incidents_extra_cost;
