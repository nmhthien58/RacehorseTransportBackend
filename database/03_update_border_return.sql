CREATE TABLE IF NOT EXISTS incident.incident_consents (
    consent_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id       integer      NOT NULL REFERENCES incident.trip_incidents (incident_id),
    booking_id        integer      NOT NULL REFERENCES booking.booking_requests (booking_id),
    customer_user_id  integer      NOT NULL REFERENCES identity.users (user_id),
    accepted          boolean      NOT NULL,
    decided_at        timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uq_incident_consents_incident_booking UNIQUE (incident_id, booking_id)
);

