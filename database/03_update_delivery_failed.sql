ALTER TABLE acceptance.handover_acceptances
    ADD COLUMN IF NOT EXISTS waiting_hours integer NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS waiting_fee numeric(18,2) NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS acceptance.delivery_failures (
    failure_id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id                    integer       NOT NULL REFERENCES fleet.trips (trip_id),
    booking_id                 integer       NOT NULL REFERENCES booking.booking_requests (booking_id),
    checkpoint_id              integer REFERENCES fleet.route_checkpoints (checkpoint_id),
    reason                     varchar(30)   NOT NULL
        CONSTRAINT ck_delivery_failures_reason CHECK (reason IN ('RecipientAbsent', 'RecipientRefused', 'RefusedInjured', 'RefusedWrongHorse')),
    note                       varchar(1000),
    photo_paths                jsonb         NOT NULL DEFAULT '[]',
    recorded_by_user_id        integer       NOT NULL REFERENCES identity.users (user_id),
    recorded_at                timestamptz   NOT NULL DEFAULT now(),
    incident_id                integer REFERENCES incident.trip_incidents (incident_id),
    waiting_hours              integer       NOT NULL DEFAULT 0,
    waiting_fee                numeric(18,2) NOT NULL DEFAULT 0,
    customer_pays              boolean       NOT NULL DEFAULT false,
    decision_due_at            timestamptz,
    decision                   varchar(30)
        CONSTRAINT ck_delivery_failures_decision CHECK (decision IN ('AlternateRecipient', 'HoldAtStable', 'ReturnToOrigin')),
    decided_at                 timestamptz,
    decided_by_system          boolean       NOT NULL DEFAULT false,
    decision_cost              numeric(18,2) NOT NULL DEFAULT 0,
    alternate_recipient_name   varchar(100),
    alternate_recipient_phone  varchar(20),
    alternate_address          varchar(255),
    alternate_lat              numeric(9,6),
    alternate_lng              numeric(9,6),
    extra_distance_km          numeric(10,2)
);

